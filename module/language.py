@lru_cache(maxsize=1)
def get_language() -> str:
    """获取全局配置文件中的界面语言。"""
    try:
        with open(file=GLOBAL_CONFIG_PATH, mode='r', encoding='UTF-8') as f:
            config: dict = yaml.safe_load(f)
        language: str = (config or {}).get('language', '')
    except Exception:  # noqa.
        language: str = ''
    return language


def _t(text: str, index: int = None):
    try:
        from module.enums import Language
        language_index: dict = Language().index
        if index is None:
            index = language_index.get(get_language(), language_index[Language.EN_US])
        if text in translations:
            return translations[text][index]
        else:
            return text
    except Exception:  # noqa.
        return text
